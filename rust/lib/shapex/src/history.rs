use std::collections::{BTreeMap, BTreeSet};

use super::{BooleanKind, PersistentId, Topology};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ChangeKind {
    /// The operation retains the input revision; tolerance-sized edits do not qualify.
    Unchanged,
    Modified,
    Split,
    Merged,
    Deleted,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Origin {
    Created {
        role: Option<CreationRole>,
    },
    Derived {
        sources: Vec<PersistentId>,
        role: DerivationRole,
    },
}

/// Kernel operation and output category responsible for derived topology.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
